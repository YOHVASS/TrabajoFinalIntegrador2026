-- =====================================================================
-- Sistema Web de Gestión de Talleres Deportivos (UNJu)
-- V1: esquema inicial según el diccionario de datos (sección 6.2 de la
-- 2.ª entrega). PostgreSQL. Claves BIGINT autoincrementales (IDENTITY),
-- salvo taller_ayudante (clave compuesta). Auditoría en TIMESTAMPTZ.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Administración del sistema
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50)  NOT NULL UNIQUE,
    descripcion VARCHAR(255) NULL,
    CONSTRAINT ck_rol_nombre CHECK (nombre IN ('ADMINISTRATIVO', 'COORDINADOR', 'ADMIN_SISTEMA',
        'RESPONSABLE_INGRESO', 'PROFESOR', 'AYUDANTE', 'AUTORIDAD_INSTITUCIONAL'))
);

CREATE TABLE usuario_sistema (
    id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol         BIGINT       NOT NULL REFERENCES rol (id_rol),
    nombre_usuario VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    nombre         VARCHAR(100) NOT NULL,
    apellido       VARCHAR(100) NOT NULL,
    estado         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE noticia (
    id_noticia        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        BIGINT       NOT NULL REFERENCES usuario_sistema (id_usuario),
    titulo            VARCHAR(150) NOT NULL,
    contenido         TEXT         NOT NULL,
    tipo              VARCHAR(20)  NOT NULL,
    fecha_publicacion TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_noticia_tipo CHECK (tipo IN ('NOTICIA', 'NOVEDAD', 'AVISO'))
);

-- ---------------------------------------------------------------------
-- Oferta deportiva
-- ---------------------------------------------------------------------
CREATE TABLE disciplina (
    id_disciplina BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(50)  NOT NULL UNIQUE,
    descripcion   VARCHAR(255) NULL
);

CREATE TABLE periodo (
    id_periodo   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(20) NOT NULL UNIQUE,
    fecha_inicio DATE        NOT NULL,
    fecha_fin    DATE        NOT NULL,
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE profesor (
    id_profesor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni         VARCHAR(15)  NOT NULL UNIQUE,
    nombre      VARCHAR(100) NOT NULL,
    apellido    VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NULL,
    telefono    VARCHAR(30)  NULL,
    id_usuario  BIGINT       NULL UNIQUE REFERENCES usuario_sistema (id_usuario)
);

CREATE TABLE ayudante (
    id_ayudante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni         VARCHAR(15)  NOT NULL UNIQUE,
    nombre      VARCHAR(100) NOT NULL,
    apellido    VARCHAR(100) NOT NULL,
    id_usuario  BIGINT       NULL UNIQUE REFERENCES usuario_sistema (id_usuario)
);

CREATE TABLE taller (
    id_taller     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_disciplina BIGINT       NOT NULL REFERENCES disciplina (id_disciplina),
    id_profesor   BIGINT       NOT NULL REFERENCES profesor (id_profesor),
    id_periodo    BIGINT       NOT NULL REFERENCES periodo (id_periodo),
    nombre        VARCHAR(100) NOT NULL,
    modalidad     VARCHAR(20)  NOT NULL,
    cupo_maximo   INTEGER      NULL,
    CONSTRAINT ck_taller_modalidad CHECK (modalidad IN ('FEMENINA', 'MASCULINA', 'MIXTA')),
    CONSTRAINT ck_taller_cupo CHECK (cupo_maximo IS NULL OR cupo_maximo > 0)
);

CREATE TABLE horario_taller (
    id_horario  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_taller   BIGINT      NOT NULL REFERENCES taller (id_taller) ON DELETE CASCADE,
    dia_semana  VARCHAR(15) NOT NULL,
    hora_inicio TIME        NOT NULL,
    hora_fin    TIME        NOT NULL,
    CONSTRAINT ck_horario_dia CHECK (dia_semana IN ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES',
        'VIERNES', 'SABADO', 'DOMINGO')),
    CONSTRAINT ck_horario_horas CHECK (hora_fin > hora_inicio)
);

CREATE TABLE taller_ayudante (
    id_taller   BIGINT NOT NULL REFERENCES taller (id_taller) ON DELETE CASCADE,
    id_ayudante BIGINT NOT NULL REFERENCES ayudante (id_ayudante) ON DELETE CASCADE,
    PRIMARY KEY (id_taller, id_ayudante)
);

-- ---------------------------------------------------------------------
-- Participantes y requisitos
-- ---------------------------------------------------------------------
CREATE TABLE participante (
    id_participante     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni                 VARCHAR(15)  NOT NULL UNIQUE,
    nombre              VARCHAR(100) NOT NULL,
    apellido            VARCHAR(100) NOT NULL,
    fecha_nacimiento    DATE         NOT NULL,
    sexo                VARCHAR(20)  NOT NULL,
    facultad            VARCHAR(100) NULL,
    email               VARCHAR(150) NOT NULL,
    telefono            VARCHAR(30)  NULL,
    foto_url            VARCHAR(255) NULL,
    qr_code             VARCHAR(100) NULL UNIQUE,
    estado_habilitacion VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    fecha_alta          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_participante_sexo CHECK (sexo IN ('FEMENINO', 'MASCULINO', 'X')),
    CONSTRAINT ck_participante_habilitacion CHECK (estado_habilitacion IN ('HABILITADO', 'NO_HABILITADO', 'PENDIENTE'))
);

CREATE TABLE tipo_documento (
    id_tipo_documento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(50) NOT NULL UNIQUE,
    obligatorio       BOOLEAN     NOT NULL DEFAULT TRUE,
    tiene_vencimiento BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE TABLE documentacion (
    id_documentacion   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante    BIGINT       NOT NULL REFERENCES participante (id_participante),
    id_tipo_documento  BIGINT       NOT NULL REFERENCES tipo_documento (id_tipo_documento),
    archivo_url        VARCHAR(255) NOT NULL,
    fecha_presentacion DATE         NOT NULL,
    fecha_vencimiento  DATE         NULL,
    estado             VARCHAR(20)  NOT NULL DEFAULT 'VIGENTE',
    CONSTRAINT ck_documentacion_estado CHECK (estado IN ('VIGENTE', 'VENCIDO', 'PENDIENTE'))
);

CREATE TABLE seguro (
    id_seguro            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante      BIGINT      NOT NULL REFERENCES participante (id_participante),
    id_periodo           BIGINT      NOT NULL REFERENCES periodo (id_periodo),
    numero_poliza        VARCHAR(50) NULL,
    fecha_pago           DATE        NOT NULL,
    vigencia_desde       DATE        NOT NULL,
    vigencia_hasta       DATE        NOT NULL,
    estado               VARCHAR(20) NOT NULL DEFAULT 'VIGENTE',
    informado_productora BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_seguro_participante_periodo UNIQUE (id_participante, id_periodo),
    CONSTRAINT ck_seguro_estado CHECK (estado IN ('VIGENTE', 'VENCIDO')),
    CONSTRAINT ck_seguro_vigencia CHECK (vigencia_hasta >= vigencia_desde)
);

CREATE TABLE apto_medico (
    id_apto_medico    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante   BIGINT       NOT NULL REFERENCES participante (id_participante),
    fecha_emision     DATE         NOT NULL,
    fecha_vencimiento DATE         NOT NULL,
    archivo_url       VARCHAR(255) NULL,
    estado            VARCHAR(20)  NOT NULL DEFAULT 'VIGENTE',
    CONSTRAINT ck_apto_estado CHECK (estado IN ('VIGENTE', 'VENCIDO')),
    CONSTRAINT ck_apto_fechas CHECK (fecha_vencimiento > fecha_emision)
);

CREATE TABLE alerta (
    id_alerta       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante BIGINT       NOT NULL REFERENCES participante (id_participante),
    tipo            VARCHAR(50)  NOT NULL,
    mensaje         VARCHAR(255) NOT NULL,
    fecha_generada  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    estado          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT ck_alerta_tipo CHECK (tipo IN ('DOCUMENTACION_VENCIDA', 'DOCUMENTACION_PENDIENTE',
        'APTO_MEDICO_POR_VENCER', 'SEGURO_VENCIDO', 'SEGURO_PROXIMO_A_VENCER')),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('ACTIVA', 'RESUELTA'))
);

-- ---------------------------------------------------------------------
-- Participación
-- ---------------------------------------------------------------------
CREATE TABLE preinscripcion (
    id_preinscripcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante   BIGINT      NOT NULL REFERENCES participante (id_participante),
    id_taller         BIGINT      NOT NULL REFERENCES taller (id_taller),
    fecha_solicitud   TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado            VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT ck_preinscripcion_estado CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'LISTA_ESPERA'))
);

CREATE TABLE inscripcion (
    id_inscripcion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante   BIGINT      NOT NULL REFERENCES participante (id_participante),
    id_taller         BIGINT      NOT NULL REFERENCES taller (id_taller),
    id_preinscripcion BIGINT      NOT NULL UNIQUE REFERENCES preinscripcion (id_preinscripcion),
    fecha_inscripcion DATE        NOT NULL,
    estado            VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT ck_inscripcion_estado CHECK (estado IN ('ACTIVA', 'BAJA'))
);

-- Un participante no puede tener dos inscripciones ACTIVAS en el mismo taller.
CREATE UNIQUE INDEX uq_inscripcion_activa
    ON inscripcion (id_participante, id_taller) WHERE estado = 'ACTIVA';

CREATE TABLE asistencia (
    id_asistencia          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_participante        BIGINT      NOT NULL REFERENCES participante (id_participante),
    id_taller              BIGINT      NOT NULL REFERENCES taller (id_taller),
    id_usuario_registro    BIGINT      NOT NULL REFERENCES usuario_sistema (id_usuario),
    fecha                  DATE        NOT NULL,
    hora_ingreso           TIME        NOT NULL,
    metodo_verificacion    VARCHAR(10) NOT NULL,
    resultado_habilitacion VARCHAR(20) NOT NULL,
    CONSTRAINT ck_asistencia_metodo CHECK (metodo_verificacion IN ('QR', 'DNI')),
    CONSTRAINT ck_asistencia_resultado CHECK (resultado_habilitacion IN ('HABILITADO', 'RECHAZADO'))
);

-- No puede haber dos ingresos HABILITADOS el mismo día, en el mismo taller, para la misma persona.
CREATE UNIQUE INDEX uq_asistencia_habilitada
    ON asistencia (id_participante, id_taller, fecha) WHERE resultado_habilitacion = 'HABILITADO';

-- ---------------------------------------------------------------------
-- Índices de apoyo a las consultas frecuentes
-- ---------------------------------------------------------------------
CREATE INDEX ix_documentacion_participante ON documentacion (id_participante);
CREATE INDEX ix_seguro_participante ON seguro (id_participante);
CREATE INDEX ix_apto_participante ON apto_medico (id_participante);
CREATE INDEX ix_alerta_participante_estado ON alerta (id_participante, estado);
CREATE INDEX ix_preinscripcion_taller_estado ON preinscripcion (id_taller, estado);
CREATE INDEX ix_inscripcion_taller_estado ON inscripcion (id_taller, estado);
CREATE INDEX ix_asistencia_taller_fecha ON asistencia (id_taller, fecha);
CREATE INDEX ix_taller_periodo ON taller (id_periodo);
